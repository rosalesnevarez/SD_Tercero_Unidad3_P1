    private void tablaPersonalMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaPersonalMouseClicked
        // TODO add your handling code here:
          int fila = tablaPersonal.getSelectedRow();
          
          lblId.setText( tablaPersonal.getValueAt(fila, 0).toString() );
          txtNombre.setText(tablaPersonal.getValueAt(fila, 1).toString());
          txtApellido.setText(tablaPersonal.getValueAt(fila, 2).toString());
          txtCorreo.setText(tablaPersonal.getValueAt(fila, 3).toString());
          txtFecha.setText(tablaPersonal.getValueAt(fila, 4).toString());
      
          String sexo = tablaPersonal.getValueAt(fila, 5).toString();
          
          if(sexo.equals("M")){
              radioMujer.setSelected(true);
              radioHombre.setSelected(false);
          }
          
           if(sexo.equals("H")){
              radioMujer.setSelected(false);
              radioHombre.setSelected(true);
          }
                    
    }//GEN-LAST:event_tablaPersonalMouseClicked

